# ------------------------------------------------------------- stats tests ----

def stats_tests_card(result: dict, context: dict) -> str:
    summary, params = result["summary"], result["params"]
    normal, sharpe, corr = summary["normality"], summary["sharpe"], summary["correlation"]
    stress = summary["stress_correlation"]
    sector_rows = pd.DataFrame([
        {"Variable": name, "H": f"{v['h_statistic']:.2f}", "p-value": f"{v['p_value']:.4f}",
         "Epsilon-squared": f"{v['epsilon_squared']:.2f}", "n": v["n"],
         "Pairs significant after BH": f"{v['pairs_significant_after_bh']} of {v['pairs_tested']}",
         "Largest pairwise |rank-biserial|": f"{v['largest_pairwise_effect']:.2f}"}
        for name, v in summary["sector_differences"].items()])
    sections = [header("Statistical tests", context)]
    sections.append(f"""This is not a predictive model. It is the set of tests behind the
"Statistical tests" panel of the Data Science Lab, documented in the same format.

## Purpose

Attach uncertainty to the figures the platform reports: are returns normal, how precisely is a
Sharpe ratio or a peer median known, which correlations are distinguishable from zero, and do
sectors differ.

## Data

Daily returns on {params['n_days']:,} dates common to all tickers, for {params['n_companies']}
companies and the Nifty 50; latest metrics from `core.metrics`. Risk-free rate
{pct(params['risk_free_rate'], 4)}.

## Methods

| Question | Test | Uncertainty reported |
|---|---|---|
| Are daily returns normal? | Jarque-Bera, with skewness and excess kurtosis | p-values, Benjamini-Hochberg adjusted |
| How precise is a Sharpe ratio? | Moving-block bootstrap, {params['sharpe_block_days']}-day blocks, {params['bootstrap_resamples']:,} resamples | 95% percentile interval |
| How precise is a peer median? | Bootstrap of the peer group | 95% percentile interval |
| Which correlations differ from zero? | Pearson correlation t-test for every pair | Benjamini-Hochberg adjusted p-values; r-squared as effect size |
| Do sectors differ? | Kruskal-Wallis, then pairwise Mann-Whitney U | Epsilon-squared and rank-biserial effect sizes; BH-adjusted pairwise p-values |
| Do correlations rise in stressed markets? | Difference in mean pairwise correlation, top-quartile market volatility vs the rest | Block-bootstrap 95% interval |

All tests use a 5% level. Multiple comparisons are corrected with {params['multiple_comparison_correction']}.

## Results

**Return distributions.** Normality is rejected for {normal['rejected_at_5pct_after_bh']} of
{normal['series_tested']} series after correction. Excess kurtosis ranges from
{normal['excess_kurtosis_min']:.2f} to {normal['excess_kurtosis_max']:.2f} (median
{normal['excess_kurtosis_median']:.2f}; 0 for a normal distribution) and skewness from
{normal['skewness_min']:.2f} to {normal['skewness_max']:.2f}. On average
{pct(normal['mean_share_beyond_3_sd'], 2)} of days are more than three standard deviations from
the mean, against 0.27% under normality: returns have fat tails, so a volatility figure alone
understates how often large moves occur.

**Sharpe ratios.** The 95% interval excludes zero for {sharpe['intervals_excluding_zero']} of
{sharpe['series']} series; the median interval is {sharpe['median_interval_width']:.2f} wide. About
five years of daily returns do not pin down a Sharpe ratio, and differences between the Sharpe
ratios shown in the app should not be read as established.

**Correlations.** Of {corr['pairs']} company pairs, {corr['significant_unadjusted']} have p < 0.05
before correction and {corr['significant_after_bh']} after. Correlations range from
{corr['min']:.2f} to {corr['max']:.2f} (median {corr['median']:.2f}). With this many observations
even a small correlation is statistically distinguishable from zero, so significance says little
here; the size of the correlation is what matters.

**Sector differences.**

{markdown_table(sector_rows)}

Epsilon-squared is the share of rank variance explained by sector. With five companies per sector
the smallest possible two-sided Mann-Whitney p-value is 0.0079, so few pairs can survive
correction for ten comparisons however large the difference; the effect sizes carry the
information.

**Stress and correlation.** Mean pairwise correlation is {stress['stressed']:.3f} on the
{stress['stressed_days']} stressed days and {stress['calm']:.3f} on the {stress['calm_days']} calm
days: a difference of {stress['difference']:+.3f} (95% interval {stress['ci_low']:+.3f} to
{stress['ci_high']:+.3f}), which {'excludes' if stress['excludes_zero'] else 'does not exclude'}
zero. Diversification across these stocks was weaker when the market was volatile.

**Peer medians.** {summary['peer_median_intervals']} bootstrap intervals are stored. With five
companies in a group an interval can only take values that occur in the group, so it mostly spans
the group's range.

## Limitations

- **Small cross-sections.** Sector tests have 25 companies in 5 groups; they can detect only large
  differences, and a non-significant result is not evidence of no difference.
- **The stress threshold uses the whole sample**, so the stressed/calm split describes the past
  and could not have been applied in real time.
- **Block length is a choice.** Sharpe intervals use 21-day blocks; other reasonable lengths
  give somewhat different widths.
- **Pearson correlation** measures linear co-movement of same-day returns only.
- **Jarque-Bera with over a thousand observations** rejects for small departures from
  normality; the kurtosis and tail-frequency figures show how large the departure is.

{NOT_FOR}""")
    return "\n".join(sections)


# ------------------------------------------------------------------ regimes ----

def regimes_card(result: dict, context: dict) -> str:
    summary, params = result["summary"], result["params"]

    def regime_table(frame: pd.DataFrame) -> str:
        return markdown_table(pd.DataFrame({
            "Regime": frame["regime"], "Days": frame["days"],
            "Share of days": frame["share_of_days"].map(pct),
            "Nifty 50 volatility": frame["market_volatility"].map(pct),
            "Mean stock volatility": frame["mean_stock_volatility"].map(pct),
            "Mean pairwise correlation": frame["mean_pairwise_correlation"].map(
                lambda v: f"{v:.3f}"),
        }))

    return "\n".join([header("Market regime detection", context), f"""## Purpose

Describe the last five years of the Nifty 50 as alternating calm and turbulent periods, and show
how volatility and correlation differed between them. **Descriptive segmentation only.**

## Data

{params['n_days']:,} daily Nifty 50 returns, and company returns on the same dates.

## Method

{params['model']}, fitted by maximum likelihood (statsmodels). Each day gets a smoothed probability
of being in the high-variance state; a day is labelled turbulent when that probability exceeds 0.5.
As a transparent comparison, a rule labels a day turbulent when {params['threshold_rule']}.

## Validation

There is no ground truth for a regime, so there is no accuracy to report and no baseline to beat.
The model is checked for convergence ({'converged' if summary['converged'] else 'DID NOT CONVERGE'})
and compared with the threshold rule: the two agree on {pct(summary['agreement_with_threshold_rule'])}
of days.

## Results

Estimated annualized volatility: {pct(summary['volatility']['calm'])} in the calm state and
{pct(summary['volatility']['turbulent'])} in the turbulent state. Expected duration:
{summary['expected_duration_days']['calm']:.0f} trading days calm,
{summary['expected_duration_days']['turbulent']:.0f} turbulent. {pct(summary['turbulent_share_of_days'])}
of days are labelled turbulent. Log-likelihood {summary['log_likelihood']:.1f}, AIC {summary['aic']:.1f}.

**By Markov-switching regime**

{regime_table(result['by_regime'])}

**By threshold rule**

{regime_table(result['by_threshold_regime'])}

## Limitations

- **Smoothed probabilities use the whole sample.** A day's label depends on what happened
  afterwards, so the labels could not have been known at the time.
- **Two states are assumed**, not found. The data were not asked whether three would fit better.
- **Higher correlation in the turbulent state is partly mechanical:** correlation estimates rise
  with volatility even when the underlying relationship is unchanged.
- **One index, five years.** Few turbulent episodes are in the sample.

## What this must not be used for

- **It is not a trading or timing signal.** The labels are fitted with hindsight.
- Predicting when the next turbulent period will start or end.
- Selecting, recommending or ranking securities. FinSight is an analytics tool, not investment advice.
"""])


# ---------------------------------------------------------------- anomalies ----

def anomaly_card(result: dict, context: dict) -> str:
    summary, params = result["summary"], result["params"]
    counts = summary["flagged_by"]
    overlap = pd.DataFrame({
        "Method A": result["overlap"]["method_a"], "Method B": result["overlap"]["method_b"],
        "Flagged by both": result["overlap"]["both"], "Only A": result["overlap"]["only_a"],
        "Only B": result["overlap"]["only_b"],
        "Jaccard overlap": result["overlap"]["jaccard"].map(lambda v: f"{v:.3f}"),
    })
    observations = summary["observations"]
    return "\n".join([header("Anomaly detection comparison (Isolation Forest)", context),
                      f"""## Purpose

Compare a machine-learning anomaly detector with the two statistical rules used elsewhere in
FinSight, on the same daily market data, and report how far they agree. Every flag is worded
"Potential data anomaly detected": a prompt to look at a data point, never a statement about a
company.

## Data

{observations:,} company-days of returns and volume (placeholder rows excluded, first
{params['rolling_window']} days of each series used as history).

## Features

`{'`, `'.join(params['features'])}`: each day's return and log volume expressed as a modified
z-score against that stock's previous {params['rolling_window']} days, plus the absolute return.
The rolling scores use only earlier data, the same as the statistical rules.

## Methods compared

| Method | Rule |
|---|---|
| IQR | Return or log volume outside {params['iqr_multiplier']:g}x IQR fences of its prior {params['rolling_window']} days |
| Modified z-score | Absolute modified z-score of return or log volume above {params['modified_zscore_threshold']:g} |
| Isolation Forest | {params['n_estimators']} trees, contamination {pct(params['contamination'])}, seed {params['seed']} |

The contamination rate was fixed at {pct(params['contamination'])} in advance. It was not set to
match the number of points the statistical rules flag.

## Validation

There are no labels saying which days are truly anomalous, so no accuracy can be computed and
there is no baseline to beat. What can be measured is agreement between methods.

## Results

| Method | Flagged | Share of observations |
|---|---|---|
| IQR | {counts['iqr']:,} | {pct(counts['iqr'] / observations, 2)} |
| Modified z-score | {counts['modified_zscore']:,} | {pct(counts['modified_zscore'] / observations, 2)} |
| Isolation Forest | {counts['isolation_forest']:,} | {pct(counts['isolation_forest'] / observations, 2)} |

{markdown_table(overlap)}

{summary['flagged_by_all_three']:,} company-days are flagged by all three methods,
{summary['flagged_by_exactly_two']:,} by exactly two and {summary['flagged_by_exactly_one']:,} by
only one. {summary['isolation_forest_only']:,} are flagged by the Isolation Forest alone. The
points flagged by all three are the ones most worth inspecting; a sample is examined by hand in
`notebooks/07_anomalies_and_regimes`.

## Limitations

- **The forest is fitted on the whole sample** (it is unsupervised and descriptive), so, unlike
  the two rules, its flags are not strictly real-time. Its input features are leakage-free.
- **Its flag count is set by the contamination parameter**, so "the forest flags 2% of days" is an
  input, not a finding. Only which days it picks is informative.
- **The methods share inputs**, so agreement between them is expected and is not independent
  confirmation.
- **Fat tails.** All three flag far more days than a normal distribution would predict; most are
  genuine large moves around news, not data errors.

## What this must not be used for

- Concluding anything about a company's conduct. A flag marks an unusual data point only.
- Removing data automatically. Nothing is deleted on the basis of a flag.
- Selecting, recommending or ranking securities. FinSight is an analytics tool, not investment advice.
"""])


