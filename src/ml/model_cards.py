def write_all(results: dict, context: dict, cards_dir: Path | None = None) -> list[Path]:
    """Write a card for every task present in `results`. Returns the paths written."""
    cards_dir = cards_dir or CARDS_DIR
    cards_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for task, (filename, build) in CARDS.items():
        if task in results:
            path = cards_dir / filename
            path.write_text(build(results[task], context), encoding="utf-8")
            written.append(path)
    return written
