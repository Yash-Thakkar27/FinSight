"""Model cards, written from the results of the run that produced them.

Each card covers: purpose, data, features, validation scheme, results against
the baseline, limitations, and what the model must not be used for. Every
number in a card is read from the result tables; none is typed by hand, so a
card cannot drift from the stored results.
"""

from pathlib import Path

import pandas as pd

from config.settings import DOCS_DIR

CARDS_DIR = DOCS_DIR / "model_cards"

NOT_FOR = """## What this must not be used for

- Predicting prices or the direction of returns, or timing trades.
- Selecting, recommending or ranking securities. FinSight is an analytics tool, not investment advice.
- Any decision where the limitations above would matter and have not been checked on newer data.
"""


def header(title: str, context: dict) -> str:
    return (f"# Model card: {title}\n\n"
            f"- Generated by `python scripts/run_ml.py` (seed {context['seed']}); "
            "every figure below is read from that run's stored results.\n"
            f"- Data snapshot id: `{context['snapshot']}` "
            f"(prices {context['price_start']} to {context['price_end']}, "
            f"{context['n_companies']} companies)\n")


def markdown_table(frame: pd.DataFrame) -> str:
    lines = ["| " + " | ".join(str(c) for c in frame.columns) + " |",
             "|" + "---|" * len(frame.columns)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in frame.itertuples(index=False)]
    return "\n".join(lines)


def pct(value, decimals=1) -> str:
    return "N/A" if value is None or pd.isna(value) else f"{value * 100:.{decimals}f}%"


def signed(value, decimals=1) -> str:
    return "N/A" if value is None or pd.isna(value) else f"{value:+.{decimals}f}%"


# --------------------------------------------------------------- volatility ----

def volatility_card(result: dict, context: dict) -> str:
    comparison, dm, folds, params = (result["comparison"], result["dm"], result["folds"],
                                     result["params"])
    sections = [header("Volatility forecasting", context)]
    sections.append(f"""## Purpose

Forecast each stock's realized volatility over the next {' and '.join(str(h) for h in params['horizons'])}
trading days, for risk measurement, and test whether a model does better than the standard naive
forecasts. Volatility is persistent and therefore forecastable; returns are not, and this model
does not attempt to forecast them.

## Data

- Daily adjusted close, high, low and volume for {params['tickers']} companies and the Nifty 50,
  from PostgreSQL (source: Yahoo Finance via yfinance). Placeholder rows are excluded.
- Target: realized variance over t+1 .. t+h, the mean of squared daily returns. Reported as
  annualized volatility (x sqrt(252)).

## Forecasters

| Name | Kind | Definition |
|---|---|---|
| `hist_21` | Baseline | Trailing 21-day realized variance |
| `ewma` | Baseline | RiskMetrics EWMA, lambda = {params['ewma_lambda']} |
| `garch` | Model | {params['garch']}; forecast variance averaged over the horizon |
| `ridge` | Model | Ridge regression (alpha = {params['ridge_alpha']}) on standardized features, pooled across companies |
| `gbm` | Model | Gradient-boosted trees ({', '.join(f'{k}={v}' for k, v in params['gbm'].items())}), pooled |

## Features (ridge and gbm)

`{'`, `'.join(params['features'])}`

Lagged realized variance over 1, 5, 21 and 63 days, the latest absolute return, volume relative to
its 21-day mean, Parkinson range-based variance over 5 and 21 days, and Nifty 50 realized variance
over 5 and 21 days. The models predict log realized variance; the forecast is exp(prediction +
half the training residual variance), the mean of a log-normal.

**Leakage controls.** Every feature at date t uses only data up to t (trailing windows). Scaling
is fitted on training rows only. Unit tests alter all data after a date and check that features
and every model's forecasts up to that date are unchanged.

## Validation

Walk-forward with an expanding window: {params['initial_train_days']} trading days before the
first test block, then blocks of {params['test_block_days']} days. Models are refitted at the start
of each block using only earlier data, and the last h training rows are purged so no training
target overlaps a test period. Random K-fold is never used. All forecasters are scored on one
common set of rows.
""")
    for horizon in sorted(folds["horizon"].unique()):
        rows = folds[folds["horizon"] == horizon]
        sections.append(f"- Horizon {horizon}: {len(rows)} folds, test dates "
                        f"{str(rows['test_start'].min())[:10]} to "
                        f"{str(rows['test_end'].max())[:10]}, "
                        f"{int(rows['test_rows'].sum()):,} forecasts.")

    sections.append("\n## Results against the baselines\n\n"
                    "RMSE and MAE are in annualized volatility (0.11 = 11 percentage points). "
                    "QLIKE is on variance; lower is better for all three. \"Change\" is relative "
                    "to the best baseline for that metric; negative means lower loss. "
                    "\"Fold mean ± sd\" shows variation across walk-forward folds.\n")
    for horizon in sorted(comparison["horizon"].unique()):
        rows = comparison[comparison["horizon"] == horizon]
        table = pd.DataFrame({
            "Metric": rows["metric"].str.upper(),
            "Forecaster": rows["model"] + " (" + rows["kind"] + ")",
            "Pooled": rows["value"].map(lambda v: f"{v:.4f}"),
            "Change vs best baseline": [
                "best baseline" if m == b else signed(c)
                for m, b, c in zip(rows["model"], rows["best_baseline"],
                                   rows["change_vs_best_baseline_pct"])],
            "Fold mean ± sd": [f"{m:.4f} ± {s:.4f}"
                               for m, s in zip(rows["fold_mean"], rows["fold_std"])],
            "Folds better than best baseline": [
                "-" if m == b else f"{w} of {n}"
                for m, b, w, n in zip(rows["model"], rows["best_baseline"],
                                      rows["folds_beating_best_baseline"], rows["folds"])],
        })
        sections.append(f"### {horizon}-day horizon\n\n{markdown_table(table)}\n")

    sections.append("### Diebold-Mariano tests (QLIKE loss, against the best baseline)\n\n"
                    "A negative statistic means lower loss than the benchmark. The pooled test "
                    "averages the loss difference across companies for each date and uses h-1 "
                    "Newey-West lags with the Harvey-Leybourne-Newbold correction.\n")
    table = pd.DataFrame({
        "Horizon": dm["horizon"], "Forecaster": dm["model"], "Benchmark": dm["benchmark"],
        "DM statistic": dm["dm_statistic"].map(lambda v: f"{v:+.2f}"),
        "p-value": dm["p_value"].map(lambda v: f"{v:.4f}"),
        "Companies significantly better (5%)": [
            f"{b} of {t}" for b, t in zip(dm["tickers_significantly_better"],
                                          dm["tickers_tested"])],
        "Significantly worse": dm["tickers_significantly_worse"],
    })
    sections.append(markdown_table(table) + "\n")

    best = {}
    for horizon in sorted(comparison["horizon"].unique()):
        rows = comparison[(comparison["horizon"] == horizon) & (comparison["metric"] == "qlike")
                          & (comparison["kind"] == "model")]
        top = rows.loc[rows["change_vs_best_baseline_pct"].idxmin()]
        test = dm[(dm["horizon"] == horizon) & (dm["model"] == top["model"])].iloc[0]
        verdict = ("beats" if top["change_vs_best_baseline_pct"] < 0 and test["p_value"] < 0.05
                   else "does not beat")
        best[horizon] = (f"- **{horizon}-day:** the best model by QLIKE is `{top['model']}`, which "
                         f"{verdict} the best baseline (`{top['best_baseline']}`): QLIKE "
                         f"{signed(top['change_vs_best_baseline_pct'])}, lower in "
                         f"{top['folds_beating_best_baseline']} of {top['folds']} folds, "
                         f"DM p = {test['p_value']:.4f}; significantly better for "
                         f"{test['tickers_significantly_better']} of {test['tickers_tested']} "
                         "companies individually.")
    sections.append("### Reading the results\n\n" + "\n".join(best.values()) + "\n")

    sections.append(f"""## Limitations

- **One market regime sample.** The test period is about three years of one market. The ranking
  of forecasters may not hold in a different volatility regime.
- **The target is a noisy proxy.** Realized variance from daily returns over 5 days is a rough
  estimate of the true variance; QLIKE is reported because it is robust to that noise.
- **Pooled coefficients.** Ridge and gbm use one set of parameters for all companies, which helps
  with limited history but ignores company-specific dynamics. The pooled improvement is not
  significant for every company individually (see the per-company counts above).
- **No hyperparameter search.** Ridge alpha and the tree settings are fixed, conventional values
  and were not tuned, so the test results are not optimistically selected. Tuning might help.
- **Overlapping forecasts.** Daily h-day forecasts overlap; the DM test allows for that, but the
  effective sample is smaller than the row count suggests.
- **GARCH assumes normal errors** and is refitted quarterly, not daily.
- **Survivorship.** The universe is 25 large companies listed today.

{NOT_FOR}""")
    return "\n".join(sections)


